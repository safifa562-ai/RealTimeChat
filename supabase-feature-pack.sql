-- RealTimeChat ultimate feature pack: statuses, status views, blocks/reports and pinned/forwarded messages.
-- Run in Supabase SQL Editor for the SAME project configured in Render. Additive: existing chats are preserved.
BEGIN;

-- Core schema bootstrap: existing tables are preserved; missing tables/columns are created.
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  avatar_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen TIMESTAMPTZ
);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS username TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS password_hash TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS avatar_url TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS last_seen TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id BIGINT NOT NULL,
  receiver_id BIGINT NOT NULL,
  message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  message_type TEXT NOT NULL DEFAULT 'text',
  file_name TEXT,
  file_url TEXT,
  file_size BIGINT,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  is_edited BOOLEAN NOT NULL DEFAULT FALSE,
  is_forwarded BOOLEAN NOT NULL DEFAULT FALSE,
  forwarded_from BIGINT
);
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS sender_id BIGINT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS receiver_id BIGINT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS message TEXT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS message_type TEXT NOT NULL DEFAULT 'text';
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS file_name TEXT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS file_url TEXT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS file_size BIGINT;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_read BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_edited BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_forwarded BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS forwarded_from BIGINT;
CREATE INDEX IF NOT EXISTS messages_sender_receiver_created_idx ON public.messages (sender_id, receiver_id, created_at);
CREATE INDEX IF NOT EXISTS messages_receiver_sender_created_idx ON public.messages (receiver_id, sender_id, created_at);

CREATE TABLE IF NOT EXISTS public.friendships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  friend_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'accepted',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, friend_id)
);
CREATE TABLE IF NOT EXISTS public.friend_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id BIGINT NOT NULL,
  receiver_id BIGINT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.group_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (group_id, user_id)
);
CREATE TABLE IF NOT EXISTS public.group_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id BIGINT NOT NULL,
  sender_id BIGINT NOT NULL,
  message TEXT,
  message_type TEXT NOT NULL DEFAULT 'text',
  file_name TEXT,
  file_url TEXT,
  file_size BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.group_messages ADD COLUMN IF NOT EXISTS message_type TEXT NOT NULL DEFAULT 'text';
ALTER TABLE public.group_messages ADD COLUMN IF NOT EXISTS file_name TEXT;
ALTER TABLE public.group_messages ADD COLUMN IF NOT EXISTS file_url TEXT;
ALTER TABLE public.group_messages ADD COLUMN IF NOT EXISTS file_size BIGINT;
ALTER TABLE public.group_messages ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
CREATE TABLE IF NOT EXISTS public.message_reactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  emoji TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (message_id, user_id, emoji)
);

CREATE TABLE IF NOT EXISTS public.user_statuses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  content TEXT,
  media_path TEXT,
  media_type TEXT NOT NULL DEFAULT 'text',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '24 hours'),
  CONSTRAINT user_statuses_content_media_check CHECK (length(COALESCE(content, '')) <= 700 OR content IS NULL),
  CONSTRAINT user_statuses_media_type_check CHECK (media_type IN ('text','image/jpeg','image/png','image/webp','video/mp4','video/webm'))
);
CREATE INDEX IF NOT EXISTS user_statuses_active_idx ON public.user_statuses (user_id, expires_at DESC);

CREATE TABLE IF NOT EXISTS public.status_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status_id BIGINT NOT NULL,
  viewer_id BIGINT NOT NULL,
  viewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (status_id, viewer_id)
);
CREATE INDEX IF NOT EXISTS status_views_status_idx ON public.status_views (status_id, viewed_at DESC);

CREATE TABLE IF NOT EXISTS public.user_blocks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  blocker_id BIGINT NOT NULL,
  blocked_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT user_blocks_no_self CHECK (blocker_id <> blocked_id),
  UNIQUE (blocker_id, blocked_id)
);
CREATE INDEX IF NOT EXISTS user_blocks_pair_idx ON public.user_blocks (blocker_id, blocked_id);
CREATE INDEX IF NOT EXISTS user_blocks_reverse_idx ON public.user_blocks (blocked_id, blocker_id);

CREATE TABLE IF NOT EXISTS public.user_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id BIGINT NOT NULL,
  reported_user_id BIGINT NOT NULL,
  reason TEXT NOT NULL CHECK (reason IN ('spam','harassment','impersonation','inappropriate-content','other')),
  details TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','reviewing','resolved','dismissed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT user_reports_no_self CHECK (reporter_id <> reported_user_id),
  CONSTRAINT user_reports_details_limit CHECK (length(COALESCE(details,'')) <= 1000)
);
CREATE INDEX IF NOT EXISTS user_reports_review_idx ON public.user_reports (status, created_at DESC);
CREATE INDEX IF NOT EXISTS user_reports_target_idx ON public.user_reports (reported_user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.pinned_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  message_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, message_id)
);
CREATE INDEX IF NOT EXISTS pinned_messages_user_idx ON public.pinned_messages (user_id, created_at DESC);

