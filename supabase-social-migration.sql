-- VibeCircle social-network feature migration for RealTimeChat.
-- Safe/additive: does not delete or rewrite existing users, messages, friends or groups.
-- Run once in Supabase SQL Editor for the SAME project configured in Render.
BEGIN;

ALTER TABLE public.users ADD COLUMN IF NOT EXISTS bio TEXT;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS display_name TEXT;

CREATE TABLE IF NOT EXISTS public.social_follows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  follower_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  following_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT social_follows_no_self CHECK (follower_id <> following_id),
  UNIQUE (follower_id, following_id)
);
CREATE INDEX IF NOT EXISTS social_follows_follower_idx ON public.social_follows (follower_id, created_at DESC);
CREATE INDEX IF NOT EXISTS social_follows_following_idx ON public.social_follows (following_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.social_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  caption TEXT,
  media_path TEXT NOT NULL,
  media_type TEXT NOT NULL CHECK (media_type IN ('image/jpeg','image/png','image/webp','video/mp4','video/webm')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT social_posts_caption_limit CHECK (length(COALESCE(caption,'')) <= 2200)
);
CREATE INDEX IF NOT EXISTS social_posts_user_idx ON public.social_posts (user_id, id DESC);
CREATE INDEX IF NOT EXISTS social_posts_created_idx ON public.social_posts (id DESC);

CREATE TABLE IF NOT EXISTS public.social_post_likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES public.social_posts(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (post_id, user_id)
);
CREATE INDEX IF NOT EXISTS social_post_likes_post_idx ON public.social_post_likes (post_id);

CREATE TABLE IF NOT EXISTS public.social_post_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES public.social_posts(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  body TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS social_post_comments_post_idx ON public.social_post_comments (post_id, id ASC);

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('social-posts','social-posts',FALSE,52428800,
  ARRAY['image/jpeg','image/png','image/webp','video/mp4','video/webm']::TEXT[])
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  public = FALSE,
  file_size_limit = 52428800,
  allowed_mime_types = EXCLUDED.allowed_mime_types;

GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.social_follows TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.social_posts TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.social_post_likes TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.social_post_comments TO service_role;
GRANT SELECT ON TABLE public.users TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

ALTER TABLE public.social_follows ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.social_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.social_post_likes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.social_post_comments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.social_follows FROM anon, authenticated;
REVOKE ALL ON TABLE public.social_posts FROM anon, authenticated;
REVOKE ALL ON TABLE public.social_post_likes FROM anon, authenticated;
REVOKE ALL ON TABLE public.social_post_comments FROM anon, authenticated;

-- Private saved-post bookmarks. Each user can save a post only once.
CREATE TABLE IF NOT EXISTS public.social_post_saves (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL REFERENCES public.social_posts(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (post_id, user_id)
);
CREATE INDEX IF NOT EXISTS social_post_saves_user_idx
  ON public.social_post_saves (user_id, created_at DESC);
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.social_post_saves TO service_role;
ALTER TABLE public.social_post_saves ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.social_post_saves FROM anon, authenticated;

NOTIFY pgrst, 'reload schema';
COMMIT;
