-- RealTimeChat message-save repair
-- Run once in Supabase Dashboard -> SQL Editor -> New query.
-- This is designed to add missing columns without deleting existing messages.

BEGIN;

CREATE TABLE IF NOT EXISTS public.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id bigint NOT NULL,
  receiver_id bigint NOT NULL,
  message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  message_type text NOT NULL DEFAULT 'text',
  file_name text,
  file_url text,
  file_size bigint,
  is_read boolean NOT NULL DEFAULT false,
  is_deleted boolean NOT NULL DEFAULT false,
  is_edited boolean NOT NULL DEFAULT false
);

-- Add fields used by the app if the existing messages table predates them.
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS sender_id bigint;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS receiver_id bigint;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS message text;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS message_type text NOT NULL DEFAULT 'text';
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS file_name text;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS file_url text;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS file_size bigint;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_read boolean NOT NULL DEFAULT false;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_deleted boolean NOT NULL DEFAULT false;
ALTER TABLE public.messages ADD COLUMN IF NOT EXISTS is_edited boolean NOT NULL DEFAULT false;

-- Keep message_type able to store both text and file/voice-note messages.
-- Convert a legacy enum/domain column to text when needed and remove only CHECK
-- constraints whose definition explicitly mentions message_type.
DO $$
DECLARE
  v_udt text;
  c record;
BEGIN
  SELECT udt_name INTO v_udt
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'messages'
    AND column_name = 'message_type';

  -- Drop only checks tied to message_type before converting a legacy enum/domain.
  FOR c IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.messages'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%message_type%'
  LOOP
    EXECUTE format('ALTER TABLE public.messages DROP CONSTRAINT %I', c.conname);
  END LOOP;

  IF v_udt IS NOT NULL AND v_udt NOT IN ('text', 'varchar', 'bpchar') THEN
    ALTER TABLE public.messages ALTER COLUMN message_type DROP DEFAULT;
    ALTER TABLE public.messages ALTER COLUMN message_type TYPE text USING message_type::text;
  END IF;

  ALTER TABLE public.messages ALTER COLUMN message_type SET DEFAULT 'text';
END $$;

-- The backend uses this role only from Render. Never expose its key in browser code.
-- Grant only the app tables that this backend is designed to use, if each exists.
GRANT USAGE ON SCHEMA public TO service_role;
DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'users', 'messages', 'friendships', 'friend_requests',
    'groups', 'group_members', 'group_messages', 'message_reactions'
  ] LOOP
    IF to_regclass(format('public.%I', table_name)) IS NOT NULL THEN
      EXECUTE format(
        'GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.%I TO service_role',
        table_name
      );
    END IF;
  END LOOP;
END $$;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

-- If the existing numeric id sequence got out of sync, align the next id.
DO $$
DECLARE
  v_seq text;
  v_type text;
  v_max bigint;
BEGIN
  SELECT data_type INTO v_type
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'messages'
    AND column_name = 'id';

  v_seq := pg_get_serial_sequence('public.messages', 'id');
  IF v_seq IS NOT NULL AND v_type IN ('smallint', 'integer', 'bigint') THEN
    EXECUTE 'SELECT COALESCE(MAX(id), 0)::bigint FROM public.messages' INTO v_max;
    PERFORM setval(v_seq, GREATEST(v_max + 1, 1), false);
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO service_role', v_seq);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS messages_sender_receiver_created_idx
  ON public.messages (sender_id, receiver_id, created_at);
CREATE INDEX IF NOT EXISTS messages_receiver_sender_created_idx
  ON public.messages (receiver_id, sender_id, created_at);

NOTIFY pgrst, 'reload schema';
COMMIT;
